module.exports = function(eleventyConfig) {
  // Static assets
  eleventyConfig.addPassthroughCopy("images");
  eleventyConfig.addPassthroughCopy("style.css");
  eleventyConfig.addPassthroughCopy("netlify");

  // Static HTML pages — copy flat to _site root, skip template processing
  const staticPages = [
    "index.html",
    "about.html",
    "services.html",
    "shop.html",
    "social.html",
    "resources.html",
    "404.html",
    "thank-you-newsletter.html",
    "thank-you-booking.html",
  ];
  staticPages.forEach((page) => {
    eleventyConfig.addPassthroughCopy(page);
    eleventyConfig.ignores.add(page);
  });

  // Per-product shop pages and the Pinterest product feed, copied through as-is like the static pages
  // above. A Pinterest catalog needs a unique product URL on a domain Pinterest can verify, and
  // marketplaces (Etsy, Gumroad) cannot be claimed — so these are the catalog's landing pages.
  // Generated by PINTEREST/_build/build-product-pages.mjs in the HQ folder; do not hand-edit.
  eleventyConfig.addPassthroughCopy("shop");
  eleventyConfig.ignores.add("shop/**");
  eleventyConfig.addPassthroughCopy("pinterest-feed.csv");

  // Deliverables pass through as-is. Eleventy was turning each start-here page into its own folder,
  // which broke the relative link to start-here.css (they rendered unstyled), and the five PDFs were
  // not being published at all.
  // Neither of these was ever published — both 404'd on the live site, so search engines had no
  // sitemap and no crawl rules.
  // Google Search Console ownership check — must be served verbatim at the site root
  eleventyConfig.addPassthroughCopy('google08cf9ffb235122eb.html');
  eleventyConfig.ignores.add('google08cf9ffb235122eb.html');

  eleventyConfig.addPassthroughCopy('robots.txt');
  eleventyConfig.addPassthroughCopy('sitemap.xml');

  // the intake pages load these; without them the forms render unstyled and inert
  eleventyConfig.addPassthroughCopy('intake');

  eleventyConfig.addPassthroughCopy('deliverables/*.html');
  eleventyConfig.addPassthroughCopy('deliverables/*.pdf');
  eleventyConfig.addPassthroughCopy('deliverables/start-here.css');
  eleventyConfig.ignores.add('deliverables/**');

  // blog.html is generated by blog.njk — ignore the static copy
  eleventyConfig.ignores.add("blog.html");

  // Internal/operational files — never publish
  eleventyConfig.ignores.add(".claude/**");
  eleventyConfig.ignores.add("content-audit/**");
  eleventyConfig.ignores.add("products/**");
  eleventyConfig.ignores.add("node_modules/**");

  // Date filter for post display
  eleventyConfig.addFilter("postDate", (dateStr) => {
    const d = dateStr instanceof Date ? dateStr : new Date(dateStr + "T12:00:00");
    return new Intl.DateTimeFormat("en-US", {
      year: "numeric",
      month: "long",
      day: "numeric",
    }).format(d);
  });

  // Short date for structured data
  eleventyConfig.addFilter("isoDate", (dateStr) => {
    const d = dateStr instanceof Date ? dateStr : new Date(dateStr + "T12:00:00");
    return d.toISOString().slice(0, 10);
  });

  return {
    dir: {
      input: ".",
      output: "_site",
      includes: "_includes",
    },
    htmlTemplateEngine: false,
    markdownTemplateEngine: "njk",
  };
};
